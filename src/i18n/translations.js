export const SUPPORTED_LANGS = ['pt-BR', 'en', 'es', 'fr', 'de', 'ja', 'ko'];
export const LANG_LABELS = { 'pt-BR': '🇧🇷 Português', en: '🇺🇸 English', es: '🇪🇸 Español', fr: '🇫🇷 Français', de: '🇩🇪 Deutsch', ja: '🇯🇵 日本語', ko: '🇰🇷 한국어' };

export function detectLang() {
  try {
    const saved = localStorage.getItem('vamort_lang');
    if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
  } catch {}
  const nav = typeof navigator === 'undefined' ? 'en' : navigator.language || 'en';
  if (nav.startsWith('pt')) return 'pt-BR';
  if (nav.startsWith('es')) return 'es';
  if (nav.startsWith('fr')) return 'fr';
  if (nav.startsWith('de')) return 'de';
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('ko')) return 'ko';
  return 'en';
}
